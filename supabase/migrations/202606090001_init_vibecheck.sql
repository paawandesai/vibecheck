comment on column public.reports.authorization_artifact is
  'Supabase gated-check authorization artifact: scan ID, target origin, timestamp, checkbox text version, and privacy-safe requester fingerprint.';
comment on table public.rate_limit_events is
  'Server-side scan rate limit events. Required in production so Vercel/serverless instances fail closed instead of relying on memory.';
